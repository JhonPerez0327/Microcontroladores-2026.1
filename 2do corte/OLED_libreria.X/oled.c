/* =========================================
 * FUNCIONES OLED
 * ========================================= */

void OLED_Comando(unsigned char cmd){
    I2C_Start(OLED_ADDR);
    I2C_Write(OLED_CMD);
    I2C_Write(cmd);
    I2C_Stop();
}

void OLED_Dato(unsigned char dato){
    I2C_Start(OLED_ADDR);
    I2C_Write(OLED_DATA);
    I2C_Write(dato);
    I2C_Stop();
}

void OLED_Clear(void){
    unsigned char i, j;

    for(i = 0; i < 8; i++){
        OLED_Comando(0xB0 | i);
        OLED_Comando(0x00);
        OLED_Comando(0x10);

        for(j = 0; j < 128; j++){
            OLED_Dato(0x00);
        }
    }
}

void OLED_SetCursor(unsigned char pagina, unsigned char col){
    OLED_Comando(0xB0 | pagina);
    OLED_Comando(col & 0x0F);
    OLED_Comando(0x10 | ((col >> 4) & 0x0F));
}

void OLED_Init(void){
    __delay_ms(100);

    OLED_Comando(0xAE); // display off
    OLED_Comando(0xD5);
    OLED_Comando(0x80);
    OLED_Comando(0xA8);
    OLED_Comando(0x3F);
    OLED_Comando(0xD3);
    OLED_Comando(0x00);
    OLED_Comando(0x40);
    OLED_Comando(0x8D);
    OLED_Comando(0x14);
    OLED_Comando(0x20);
    OLED_Comando(0x00);
    OLED_Comando(0xA1);
    OLED_Comando(0xC8);
    OLED_Comando(0xDA);
    OLED_Comando(0x12);
    OLED_Comando(0x81);
    OLED_Comando(0xCF);
    OLED_Comando(0xD9);
    OLED_Comando(0xF1);
    OLED_Comando(0xDB);
    OLED_Comando(0x40);
    OLED_Comando(0xA4);
    OLED_Comando(0xA6);
    OLED_Comando(0xAF); // display ON

    __delay_ms(10);
    OLED_Clear();
}

void OLED_Char(unsigned char c){
    unsigned char i;

    if(c < 32 || c > 126) c = 32;

    for(i = 0; i < 5; i++){
        OLED_Dato(font5x8[c - 32][i]);
    }

    OLED_Dato(0x00);
}

void OLED_String(unsigned char pagina, unsigned char col, const char *texto){
    OLED_SetCursor(pagina, col);

    while(*texto){
        OLED_Char(*texto);
        texto++;
    }
}